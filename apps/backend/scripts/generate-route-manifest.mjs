import { readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const backendRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const handlersRoot = join(backendRoot, "src/routes/handlers");
const outFile = join(backendRoot, "src/routes/route-manifest.ts");

function handlerPathToApiRoute(relativePath) {
  const withoutRoute = relativePath.replace(/\/route\.ts$/, "");
  const segments = withoutRoute.split("/").map((seg) => {
    if (seg.startsWith("[") && seg.endsWith("]")) {
      return `:${seg.slice(1, -1)}`;
    }
    return seg;
  });
  return `/api/${segments.join("/")}`;
}

function findRouteFiles(dir) {
  const results = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      results.push(...findRouteFiles(full));
    } else if (entry === "route.ts") {
      results.push(full);
    }
  }
  return results.sort();
}

const routeFiles = findRouteFiles(handlersRoot);

const entries = routeFiles.map((file) => {
  const rel = relative(join(backendRoot, "src/routes"), file)
    .replace(/\\/g, "/")
    .replace(/\.ts$/, ".js");
  const relFromHandlers = relative(handlersRoot, file).replace(/\\/g, "/");
  const apiPath = handlerPathToApiRoute(relFromHandlers);
  return `  { path: "${apiPath}", loadHandlers: () => import("./${rel}") },`;
});

const content = `// Generated by scripts/generate-route-manifest.mjs — do not edit manually.
export const ROUTE_MANIFEST = [
${entries.join("\n")}
];
`;

writeFileSync(outFile, content, "utf8");
console.log(`Wrote ${routeFiles.length} lazy routes to src/routes/route-manifest.ts`);
