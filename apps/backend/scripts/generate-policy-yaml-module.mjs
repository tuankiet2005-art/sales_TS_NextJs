import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const backendRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(backendRoot, "src/server/config/data");
const outFile = join(backendRoot, "src/server/config/policy-yaml-content.ts");

const files = {
  FEE_POLICY_YAML: "fee-policy.yml",
  DEALER_POLICY_YAML: "dealer-policy.yml",
  LICENSE_PLATE_REGIONS_YAML: "license-plate-regions.yml",
};

let source = "// Generated by scripts/generate-policy-yaml-module.mjs — do not edit.\n\n";

for (const [exportName, filename] of Object.entries(files)) {
  const content = readFileSync(join(dataDir, filename), "utf8");
  source += `export const ${exportName} = ${JSON.stringify(content)};\n\n`;
}

writeFileSync(outFile, source);
console.log("Wrote policy YAML module to src/server/config/policy-yaml-content.ts");
