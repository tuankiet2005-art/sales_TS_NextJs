import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const backendRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const templatePath = join(
  backendRoot,
  "src/server/assets/quote-report/bang-bao-gia.xlsx",
);
const outFile = join(backendRoot, "src/server/modules/quote/quote-template-buffer.ts");

const base64 = readFileSync(templatePath).toString("base64");

const source = `// Generated by scripts/generate-quote-template-module.mjs — do not edit.

export const QUOTE_REPORT_TEMPLATE_BASE64 = ${JSON.stringify(base64)};
`;

writeFileSync(outFile, source);
console.log("Wrote quote template buffer to src/server/modules/quote/quote-template-buffer.ts");
