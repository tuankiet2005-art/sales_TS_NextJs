/**
 * Generates db/location-districts-seed.sql from vietnam-divisions-js (696 former Quận/Huyện).
 * Maps old provinces to today's 34 OnRoad locations via NQ 202/2025 province merges.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Districts, Migration, v3 } from "vietnam-divisions-js";

const NEON_TO_V3 = {
  HN: "HNI",
  HP: "HPG",
  BN: "BNH",
  CB: "CBG",
  DB: "DBN",
  HY: "HYN",
  LC: "LCU",
  LS: "LSN",
  LO: "LCI",
  NB: "NBH",
  PT: "PTO",
  QN: "QNH",
  SL: "SLA",
  TN: "TNN",
  TQ: "TGQ",
  HUE: "TTH",
  DN: "DNG",
  HT: "HTH",
  KH: "KHA",
  NA: "NAN",
  QNG: "QNI",
  QT: "QTI",
  TH: "THA",
  GL: "GLI",
  DLK: "DLK",
  LD: "LDG",
  HCM: "HCM",
  CT: "CTO",
  AG: "AGG",
  CM: "CMU",
  DNI: "DNI",
  DT: "DTP",
  TNI: "TNH",
  VL: "VLG",
};

/** Neon seed id order matches locations INSERT ids 1..34 */
const NEON_LOCATION_IDS = {
  HN: 1,
  HP: 2,
  BN: 3,
  CB: 4,
  DB: 5,
  HY: 6,
  LC: 7,
  LS: 8,
  LO: 9,
  NB: 10,
  PT: 11,
  QN: 12,
  SL: 13,
  TN: 14,
  TQ: 15,
  HUE: 16,
  DN: 17,
  HT: 18,
  KH: 19,
  NA: 20,
  QNG: 21,
  QT: 22,
  TH: 23,
  GL: 24,
  DLK: 25,
  LD: 26,
  HCM: 27,
  CT: 28,
  AG: 29,
  CM: 30,
  DNI: 31,
  DT: 32,
  TNI: 33,
  VL: 34,
};

function sqlEscape(value) {
  return value.replace(/'/g, "''");
}

function stripAdministrativePrefix(name) {
  return name
    .replace(/^Thành phố\s+/i, "")
    .replace(/^Tỉnh\s+/i, "")
    .replace(/^Thị xã\s+/i, "")
    .replace(/^Huyện\s+/i, "")
    .replace(/^Quận\s+/i, "")
    .trim();
}

const districts = await Districts.getAllDistricts();
const merges = await Migration.getAllMergedProvinces();
const v3provinces = await v3.getAllProvinces();
const v3ByCode = Object.fromEntries(v3provinces.map((p) => [p.code, p]));

const oldToNewV3Id = new Map();
for (const merge of merges) {
  for (const from of merge.mergedFrom) {
    oldToNewV3Id.set(from.oldProvinceId, merge.newProvinceId);
  }
}
for (const p of v3provinces) {
  if (!oldToNewV3Id.has(p.idProvince)) {
    oldToNewV3Id.set(p.idProvince, p.idProvince);
  }
}

const v3IdToNeon = {};
for (const [neonCode, v3Code] of Object.entries(NEON_TO_V3)) {
  const v3Province = v3ByCode[v3Code];
  if (!v3Province) {
    throw new Error(`Missing v3 province for neon code ${neonCode}`);
  }
  v3IdToNeon[v3Province.idProvince] = neonCode;
}

const rows = [];
for (const district of districts) {
  const newV3Id = oldToNewV3Id.get(district.idProvince) ?? district.idProvince;
  const neonCode = v3IdToNeon[newV3Id];
  if (!neonCode) {
    throw new Error(`No neon mapping for v3 province id ${newV3Id} (${district.name})`);
  }
  const locationId = NEON_LOCATION_IDS[neonCode];
  const code = `${district.idProvince}-${district.idDistrict}`;
  const name = district.name.trim();
  const nameEn = stripAdministrativePrefix(name);
  rows.push({ locationId, code, name, nameEn });
}

rows.sort((a, b) => a.locationId - b.locationId || a.name.localeCompare(b.name, "vi"));

const header = `-- Former Quận/Huyện (pre-2025), grouped under today's 34 OnRoad provinces.
-- Generated by web/scripts/generate-district-seed.mjs — do not edit by hand.
-- Source: vietnam-divisions-js (CC data) + NQ 202/2025 province merge map.

`;

const body =
  rows
    .map(
      (row) =>
        `(${row.locationId}, '${sqlEscape(row.code)}', '${sqlEscape(row.name)}', '${sqlEscape(row.nameEn)}', '${sqlEscape(row.name)}', '${sqlEscape(row.name)}')`,
    )
    .join(",\n");

const sql = `${header}INSERT INTO location_districts (location_id, code, name, name_en, name_zh, name_ja) VALUES\n${body};\n`;

const outPath = join(dirname(fileURLToPath(import.meta.url)), "../../db/location-districts-seed.sql");
writeFileSync(outPath, sql, "utf8");
console.log(`Wrote ${rows.length} districts to ${outPath}`);
