/**
 * Creates location_districts and seeds 696 former Quận/Huyện rows when empty.
 * Usage (from web/): npm run seed:location-districts
 */
import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { neon } from "@neondatabase/serverless";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const envLocal = readFileSync(join(root, "web/.env.local"), "utf8");
const databaseUrlMatch = envLocal.match(/^DATABASE_URL=(.+)$/m);
if (!databaseUrlMatch) {
  throw new Error("DATABASE_URL not found in web/.env.local");
}
const databaseUrl = databaseUrlMatch[1].trim().replace(/^["']|["']$/g, "");

const sql = neon(databaseUrl);
const seedJsonPath = join(root, "db/location-districts-seed.json");

await sql`
  CREATE TABLE IF NOT EXISTS location_districts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT       NOT NULL REFERENCES locations(id),
    code        VARCHAR(32)  NOT NULL UNIQUE,
    name        VARCHAR(160) NOT NULL,
    name_en     VARCHAR(160) NOT NULL,
    name_zh     VARCHAR(160) NOT NULL,
    name_ja     VARCHAR(160) NOT NULL
  )
`;

await sql`
  CREATE INDEX IF NOT EXISTS idx_location_districts_location ON location_districts(location_id)
`;

const countRows = await sql`SELECT COUNT(*)::int AS count FROM location_districts`;
const existing = countRows[0]?.count ?? 0;

if (existing > 0) {
  console.log(`location_districts already has ${existing} rows — skip seed`);
  process.exit(0);
}

if (!existsSync(seedJsonPath)) {
  throw new Error(`Missing ${seedJsonPath} — run npm run generate:district-seed first`);
}

const rows = JSON.parse(readFileSync(seedJsonPath, "utf8"));
const batchSize = 50;

for (let index = 0; index < rows.length; index += batchSize) {
  const batch = rows.slice(index, index + batchSize);
  for (const row of batch) {
    await sql`
      INSERT INTO location_districts (location_id, code, name, name_en, name_zh, name_ja)
      VALUES (
        ${row.locationId},
        ${row.code},
        ${row.name},
        ${row.nameEn},
        ${row.name},
        ${row.name}
      )
      ON CONFLICT (code) DO NOTHING
    `;
  }
}

const afterRows = await sql`SELECT COUNT(*)::int AS count FROM location_districts`;
console.log(`Seeded ${afterRows[0]?.count ?? 0} location_districts rows`);
